#!/usr/bin/env python3
"""Parse results/B/server_*.log (and results/B_rerun_sglang_s64_n128/ for the rerun, Amendment 3) and write results/B/TABLE.md (Item B, slot memory)."""
import re, sys, pathlib

B = pathlib.Path(__file__).parent / "results" / "B"
RERUN = pathlib.Path(__file__).parent / "results" / "B_rerun_sglang_s64_n128"
CONFIGS = [("vllm", 16, 32), ("vllm", 32, 32), ("vllm", 64, 32), ("vllm", 64, 128),
           ("sglang", 16, 32), ("sglang", 32, 32), ("sglang", 64, 32), ("sglang", 64, 128)]
RE_V_KV = re.compile(r"Available KV cache memory: ([0-9.]+) GiB")
RE_V_TOK = re.compile(r"GPU KV cache size: ([0-9,]+) tokens")
RE_V_W = re.compile(r"Actual usage is ([0-9.]+) GiB for consumed memory \(weights \+ non-torch\)")
RE_S = re.compile(r"#tokens: (\d+), K size: ([0-9.]+) GB, V size: ([0-9.]+) GB")

def one(rx, text, name):
    m = rx.findall(text)
    if len(m) != 1:
        sys.exit(f"{name}: expected exactly one match for {rx.pattern}, found {len(m)}")
    return m[0]

rows_v, rows_s = [], []
for eng, s, n in CONFIGS:
    name = f"{eng}_s{s}_n{n}"
    p = B / f"server_{name}.log"
    if name == "sglang_s64_n128" and not p.exists():
        p = RERUN / f"server_{name}.log"   # attempt 2 refused this start (GPU not idle); the rerun is Amendment 3
    if not p.exists():
        sys.exit(f"missing {p}")
    t = p.read_text(errors="replace")
    if eng == "vllm":
        kv = one(RE_V_KV, t, name); w = one(RE_V_W, t, name); tk = int(one(RE_V_TOK, t, name).replace(",", ""))
        rows_v.append((s, n, float(kv), float(w), tk))
    else:
        tok, k, v = one(RE_S, t, name)
        rows_s.append((s, n, int(tok), k, v))

out = ["# Item B: slot memory (generated by tabulate_B.py; do not edit)", "",
       "One server start per configuration, no repeats, so no variance. Model Qwen2.5-1.5B, LoRA rank 16, seven target modules.", "",
       "## vLLM", "", "| slots | adapters | KV cache size (tokens) | tokens vs 16 slots | Available KV cache memory (GiB) | GiB vs 16 slots | consumed memory, weights + non-torch (GiB) |", "|---|---|---|---|---|---|---|"]
base = rows_v[0][2]; tbase = rows_v[0][4]
for s, n, kv, w, tk in rows_v:
    out.append(f"| {s} | {n} | {tk:,} | {100*(tk-tbase)/tbase:+.1f}% | {kv:.2f} | {100*(kv-base)/base:+.1f}% | {w:.2f} |")
out += ["", "## SGLang", "", "| slots | adapters | KV tokens | K size (GB) | V size (GB) | tokens vs 16 slots |", "|---|---|---|---|---|---|"]
sb = next(r[2] for r in rows_s if isinstance(r, tuple))
for r in rows_s:
    if isinstance(r, str): out.append(r); continue
    s, n, tok, k, v = r
    out.append(f"| {s} | {n} | {tok:,} | {k} | {v} | {100*(tok-sb)/sb:+.1f}% |")
v16, v64 = rows_v[0], rows_v[2]
out += ["", "## Derived", "",
        f"- vLLM, 16 to 64 slots at 32 adapters: {v64[2]-v16[2]:+.2f} GiB KV ({100*(v64[2]-v16[2])/v16[2]:+.1f}%); consumed memory {v64[3]-v16[3]:+.2f} GiB; about {(v16[2]-v64[2])*1024/(64-16):.0f} MiB of KV per added slot.",
        f"- vLLM, 64 slots: 32 adapters {rows_v[2][2]:.2f} GiB KV and {rows_v[2][3]:.2f} GiB consumed; 128 adapters {rows_v[3][2]:.2f} GiB KV and {rows_v[3][3]:.2f} GiB consumed.",
        "", "## Note", "",
        "The nvidia-smi column in summary.tsv is set by the 0.85 memory-utilization flag (the engines reserve a fixed fraction of the GPU) and does not measure slot cost. The KV figures above are what the engines report.", ""]
(B / "TABLE.md").write_text("\n".join(out))
print("\n".join(out))
